-- 1. JADUAL REKOD PENILAIAN MURID (Assessment Records)
CREATE TABLE IF NOT EXISTS public.assessment_records (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pupil_name TEXT NOT NULL CHECK (char_length(pupil_name) BETWEEN 1 AND 80),
  score INTEGER NOT NULL CHECK (score >= 0 AND score <= 5),
  total_questions INTEGER NOT NULL DEFAULT 5,
  achievement_title TEXT NOT NULL,
  answers_json JSONB NOT NULL DEFAULT '[]'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. JADUAL MAKLUM BALAS MURID (Suara Penjelajah Taman)
CREATE TABLE IF NOT EXISTS public.pupil_feedback (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  display_name TEXT NOT NULL DEFAULT 'Penjelajah Taman',
  ease_of_use TEXT NOT NULL,
  favorite_activity TEXT NOT NULL,
  numberline_helpful TEXT NOT NULL,
  comment TEXT DEFAULT '',
  is_approved BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. AKTIFKAN ROW LEVEL SECURITY (RLS) PADA KEDUA-DUA JADUAL
ALTER TABLE public.assessment_records ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pupil_feedback ENABLE ROW LEVEL SECURITY;

-- 4. POLISI KESELAMATAN UNTUK `assessment_records`
-- Murid (pengguna awam / anon) dibenarkan menghantar skor ujian baharu sahaja
CREATE POLICY "Allow public insert of assessment records"
ON public.assessment_records
FOR INSERT
TO anon, authenticated
WITH CHECK (true);

-- Hanya guru yang log masuk (authenticated) dibenarkan membaca semua rekod murid
CREATE POLICY "Allow authenticated teachers to read all records"
ON public.assessment_records
FOR SELECT
TO authenticated
USING (true);

-- Hanya guru yang log masuk dibenarkan memadam rekod jika perlu
CREATE POLICY "Allow authenticated teachers to delete records"
ON public.assessment_records
FOR DELETE
TO authenticated
USING (true);

-- 5. POLISI KESELAMATAN UNTUK `pupil_feedback`
-- Murid dibenarkan menghantar maklum balas (tanpa mengumpul emel/data peribadi)
CREATE POLICY "Allow public insert of pupil feedback"
ON public.pupil_feedback
FOR INSERT
TO anon, authenticated
WITH CHECK (true);

-- Semua pengguna boleh membaca maklum balas yang diluluskan (is_approved = true)
CREATE POLICY "Allow public read of approved feedback"
ON public.pupil_feedback
FOR SELECT
TO anon, authenticated
USING (is_approved = true);

-- Guru yang log masuk boleh mengemas kini atau memadam maklum balas (Moderasi)
CREATE POLICY "Allow authenticated teachers to moderate feedback"
ON public.pupil_feedback
FOR ALL
TO authenticated
USING (true)
WITH CHECK (true);